async function output(id, frames, width, height, fps, states = {}) {
  const baseId = Object.keys(names).find((key) => id === key || id.startsWith(key + '-'));
  const label = baseId
    ? names[baseId] + (id === baseId ? '' : ' · ' + id.slice(baseId.length + 1))
    : id;
  const sheet = await sharp({
    create: { width: width * frames.length, height, channels: 4, background: '#00000000' },
  })
    .composite(frames.map((input, i) => ({ input, left: i * width, top: 0 })))
    .png()
    .toBuffer();
  await writeFile(path.join(out, `${id}.png`), sheet);
  await sharp(sheet)
    .webp({ lossless: true })
    .toFile(path.join(out, `${id}.webp`));
  await mkdir(path.join(out, 'keyframes', id), { recursive: true });
  for (let i = 0; i < frames.length; i++)
    await writeFile(
      path.join(out, 'keyframes', id, `${String(i + 1).padStart(2, '0')}.png`),
      frames[i],
    );
  manifest.sprites[id] = {
    label,
    file: `${id}.webp`,
    png: `${id}.png`,
    width,
    height,
    frames: frames.length,
    fps,
    duration: fps ? frames.length / fps : 0,
    states,
    keyframes: frames.map((_, i) => ({
      index: i,
      x: i * width,
      y: 0,
      width,
      height,
      file: `keyframes/${id}/${String(i + 1).padStart(2, '0')}.png`,
    })),
  };
  css += `@keyframes sprite-${id} { to { transform: translateX(-100%); } }\n`;
  // Piskel native JSON: one editable layer with a horizontal base64 PNG chunk.
  await writeFile(
    path.join(source, `${id}.piskel`),
    JSON.stringify({
      modelVersion: 2,
      piskel: {
        name: label,
        description: 'Fan-art sprites created with AI assistance',
        fps: Math.max(1, fps),
        width,
        height,
        layers: [
          JSON.stringify({
            name: 'Keyframes',
            opacity: 1,
            frameCount: frames.length,
            chunks: [
              {
                layout: [frames.map((_, i) => i)],
                base64PNG: 'data:image/png;base64,' + sheet.toString('base64'),
              },
            ],
          }),
        ],
      },
    }),
  );
  preview.push(id);
}
for (const [id, def] of Object.entries(definitions)) {
  const input = path.join(source, `${id}-source.png`);
  const meta = await sharp(input).metadata();
  const cols = def.columns ?? 5,
    rows = def.rows ?? 2;
  const parts = [];
  for (let i = 0; i < cols * rows; i++) {
    const left = Math.round(((i % cols) * meta.width) / cols),
      top = Math.round((Math.floor(i / cols) * meta.height) / rows);
    const width = Math.round((((i % cols) + 1) * meta.width) / cols) - left,
      height = Math.round(((Math.floor(i / cols) + 1) * meta.height) / rows) - top;
    const cropped = await sharp(input).extract({ left, top, width, height }).png().toBuffer();
    const part = await sharp(cropped)
      .trim({ background: '#00000000', threshold: 20 })
      .png()
      .toBuffer();
    const m = await sharp(part).metadata();
    parts.push({ part, width: m.width, height: m.height });
  }
  const scale = Math.min(
    (def.grid[0] - 2) / Math.max(...parts.map((p) => p.width)),
    (def.grid[1] - 2) / Math.max(...parts.map((p) => p.height)),
  );
  const frames = [];
  for (const p of parts) {
    const w = Math.max(1, Math.round(p.width * scale)),
      h = Math.max(1, Math.round(p.height * scale));
    const data = await sharp(p.part)
      .resize(w, h, { kernel: 'nearest' })
      .ensureAlpha()
      .raw()
      .toBuffer();
    for (let i = 0; i < data.length; i += 4) {
      if (data[i + 3] < 128) {
        data[i + 3] = 0;
        continue;
      }
      const nearest = palette.reduce(
        (best, c) => {
          const d = c.reduce((s, n, j) => s + (n - data[i + j]) ** 2, 0);
          return d < best.d ? { c, d } : best;
        },
        { d: Infinity },
      ).c;
      data.set(nearest, i);
      data[i + 3] = 255;
    }
    const small = await sharp(data, { raw: { width: w, height: h, channels: 4 } })
      .png()
      .toBuffer();
    const cell = await sharp({
      create: { width: def.grid[0], height: def.grid[1], channels: 4, background: '#00000000' },
    })
      .composite([
        { input: small, left: Math.floor((def.grid[0] - w) / 2), top: def.grid[1] - h - 1 },
      ])
      .png()
      .toBuffer();
    frames.push(
      await sharp(cell)
        .resize(...def.size, { kernel: 'nearest' })
        .png()
        .toBuffer(),
    );
  }
  const order = Object.values(def.states).flat();
  let start = 0;
  const states = {};
  for (const [name, indices] of Object.entries(def.states)) {
    states[name] = { start, frames: indices.length, fps: def.fps, file: `${id}-${name}.webp` };
    start += indices.length;
  }
  await output(
    id,
    order.map((i) => frames[i]),
    ...def.size,
    def.fps,
    states,
  );
  for (const [name, indices] of Object.entries(def.states))
    await output(
      `${id}-${name}`,
      indices.map((i) => frames[i]),
      ...def.size,
      def.fps,
    );
}

// Small interface ornaments are code-native pixel drawings, not generated character art.
async function icon(id, width, height, body) {
  const frame = await sharp(
    Buffer.from(
      `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" shape-rendering="crispEdges">${body}</svg>`,
    ),
  )
    .png()
    .toBuffer();
  await output(id, [frame], width, height, 0);
}
